#!/usr/bin/env python3
"""Bake articles/*.md + articles/manifest.json into articles-data.js.

The pages are static (GitHub Pages has no build step), so the generated file is
committed. Articles then load synchronously — no runtime fetch, no loading state,
and the site works from file:// as well as over HTTP.

Usage:
    python3 build-articles.py          # (re)generate articles-data.js
    python3 build-articles.py --check  # exit 1 if the committed file is stale
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "articles-data.js"
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def title_of(md):
    for line in md.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return "Untitled"


def mins_of(md):
    return max(1, round(len(md.split()) / 200))


def build():
    manifest = json.loads((ROOT / "articles" / "manifest.json").read_text(encoding="utf-8"))
    seen = set()
    articles = []
    for item in manifest:
        file = item["file"]
        slug = item.get("slug") or re.sub(r"\.md$", "", file)
        if not SLUG_RE.match(slug):
            raise ValueError(f"{file}: invalid slug {slug!r} (use lowercase words separated by dashes)")
        if slug in seen:
            raise ValueError(f"{file}: duplicate slug {slug!r}")
        seen.add(slug)
        path = ROOT / "articles" / file
        if not path.is_file():
            raise ValueError(f"missing article file: {path}")
        md = path.read_text(encoding="utf-8")
        articles.append({
            "slug": slug,
            "file": file,
            "date": item["date"],
            "tags": item.get("tags", []),
            "title": title_of(md),
            "mins": mins_of(md),
            "lang": item.get("lang", "ar"),
            "dir": item.get("dir", "rtl"),
            "content": md,
        })
    articles.sort(key=lambda a: a["date"], reverse=True)
    data = json.dumps(articles, ensure_ascii=False, indent=2)
    output = "// generated by build-articles.py — do not edit by hand\nwindow.HMH_ARTICLES = " + data + ";\n"
    return output, len(articles)


if __name__ == "__main__":
    try:
        output, count = build()
    except (ValueError, KeyError) as exc:
        print(f"build-articles.py: {exc}", file=sys.stderr)
        sys.exit(1)

    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != output:
            print("articles-data.js is stale — run: python3 build-articles.py", file=sys.stderr)
            sys.exit(1)
        print("articles-data.js is up to date")
    else:
        OUT.write_text(output, encoding="utf-8")
        print(f"built articles-data.js ({count} article{'s' if count != 1 else ''})")
